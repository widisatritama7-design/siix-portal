                        const blob = new Blob(this.chunks, { type: this.mimeType || 'video/webm' });
                        this.chunks = [];
                        this.uploadCameraBlob(blob);
                    };

                    this.mediaRecorder.start(5000);

                    this.recordingActive = true;
                    this.recordingSeconds = 0;
                    this.recordingDuration = '00:00';

