                    this.mimeType = '';
                    for (const m of candidates) {
                        if (MediaRecorder.isTypeSupported(m)) { this.mimeType = m; break; }
                    }

                    this.mediaRecorder = new MediaRecorder(this.recordStream, {
                        mimeType: this.mimeType || undefined,
                        videoBitsPerSecond: 250000,
