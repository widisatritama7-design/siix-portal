                document.getElementById('beep-sound')?.play();
                setTimeout(focusScanInput, 200);
            });

            // Focus after error sound
            window.Livewire.find('<?php echo e($_instance->getId()); ?>').on('error-sound', function () {
                document.getElementById('error-sound')?.play();
                setTimeout(focusScanInput, 200);
            });

            // Focus after redirect
            window.Livewire.find('<?php echo e($_instance->getId()); ?>').on('redirect-to-leader', function () {
                setTimeout(function() {
                    window.location.href = '<?php echo e(route("pcb-scan.leader.index")); ?>';
                }, 2000);
            });

            // Keyboard shortcut: Ctrl+Shift+F to focus
            document.addEventListener('keydown', function(e) {
                if (e.ctrlKey && e.shiftKey && e.key === 'F') {
                    e.preventDefault();
                    focusScanInput();
                }
            });

            // Click anywhere on the scanner card to focus
            document.querySelector('.cursor-text')?.addEventListener('click', function(e) {
